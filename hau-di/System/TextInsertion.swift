// MARK: - Layout tastatura

enum KeyboardLayout {
    /// Codul de tasta care produce caracterul dat in layout-ul curent (ex: "v" pentru ⌘V pe Dvorak).
    static func keyCode(for character: Character) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let rawLayout = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else {
            return nil
        }
        let layoutData = Unmanaged<CFData>.fromOpaque(rawLayout).takeUnretainedValue() as Data
        let target = String(character).lowercased()
        let keyboardType = UInt32(LMGetKbdType())
        let maxLength = 4

        return layoutData.withUnsafeBytes { (buffer: UnsafeRawBufferPointer) -> CGKeyCode? in
            guard let base = buffer.baseAddress else { return nil }
            let layout = base.assumingMemoryBound(to: UCKeyboardLayout.self)
            for code in 0..<128 {
                var deadKeyState: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: maxLength)
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDisplay), 0, keyboardType,
                                            OptionBits(1), // kUCKeyTranslateNoDeadKeysMask
                                            &deadKeyState, maxLength, &length, &chars)
                if status == noErr, length > 0,
                   String(utf16CodeUnits: chars, count: length).lowercased() == target {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }

    /// ⌘V: pe QWERTY / QWERTZ / AZERTY (inclusiv layout-urile romanesti) e tasta 9.
    static var pasteKeyCode: CGKeyCode { keyCode(for: "v") ?? 9 }
}

// MARK: - Inserarea textului in campul activ

@MainActor
final class TextInserter {
    enum InsertError: LocalizedError {
        case accessibilityMissing
        case targetClosed(String)
        case targetUnreachable(String)

        var errorDescription: String? {
            switch self {
            case .accessibilityMissing:
                return "hau-di doesn't have the Accessibility permission it needs to insert text."
            case .targetClosed(let app):
                // La inceput de propozitie, cu majuscula (numele aplicatiilor raman cum sunt: "iTerm").
                let subject = app == TextInserter.unknownApp ? "The original app" : app
                return "\(subject) was closed before the dictation finished."
            case .targetUnreachable(let app):
                return "Couldn't switch back to \(app), where the dictation started."
            }
        }
    }

    /// Numele folosit in mesaje cand aplicatia de la inceputul dictarii nu are nume.
    static let unknownApp = "the original app"
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Insereaza textul acolo unde a inceput dictarea (`target`), chiar daca utilizatorul a trecut intre timp in alta
    /// fereastra sau aplicatie. Fara `target` (sau daca focusul n-a plecat de acolo), in campul activ, ca de obicei.
    func insert(_ text: String, method: InsertionMethod, restoreClipboard: Bool, target: FocusSnapshot?) async throws {
        guard AXIsProcessTrusted() else { throw InsertError.accessibilityMissing }
        var returnTo: NSRunningApplication?
        if let target, target.pid != 0, !Self.isStillFocused(target) {
            let name = target.appName ?? Self.unknownApp
            guard let app = NSRunningApplication(processIdentifier: target.pid), !app.isTerminated else {
                throw InsertError.targetClosed(name)
            }
            // 1. Direct in campul initial, fara sa schimbam fereastra (merge in majoritatea aplicatiilor native).
            if let field = target.field, await Self.insertDirectly(text, into: field.element) {
                Log.insert.info("Text inserat direct in campul initial (\(name, privacy: .public)).")
                return
            }
            // 2. Altfel aducem fereastra initiala in fata, lipim acolo, apoi revenim unde era utilizatorul.
            let current = NSWorkspace.shared.frontmostApplication
            guard await Self.bringToFront(target, app: app) else {
                throw InsertError.targetUnreachable(name)
            }
            if let current, current.processIdentifier != target.pid, current.bundleIdentifier != AppInfo.bundleID {
                returnTo = current
            }
        }
        switch method {
        case .paste:
            await paste(text, restoreClipboard: restoreClipboard)
        case .type:
            await typeCharacters(text)
        }
        if let returnTo {
            try? await Task.sleep(nanoseconds: 150_000_000)
            Self.activate(returnTo)
        }
    }

    /// Focusul e tot in campul (sau, daca nu-l stim, in aplicatia) in care a inceput dictarea.
    private static func isStillFocused(_ target: FocusSnapshot) -> Bool {
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target.pid else { return false }
        guard let field = target.field else { return true }
        let app = AXUIElementCreateApplication(target.pid)
        AXUIElementSetMessagingTimeout(app, 0.25)
        guard let current = FocusInspector.element(app, kAXFocusedUIElementAttribute as CFString) else { return true }
        return CFEqual(current, field.element)
    }

    /// Scrie textul in campul dat prin Accessibility (inlocuieste selectia sau insereaza la cursor), fara sa schimbe
    /// fereastra activa. Reusita = valoarea campului s-a schimbat; altfel nu s-a inserat nimic si se poate lipi normal.
    private static func insertDirectly(_ text: String, into field: AXUIElement) async -> Bool {
        let valueAttribute = kAXValueAttribute as CFString
        let selectedText = kAXSelectedTextAttribute as CFString
        guard let before = FocusInspector.attribute(field, valueAttribute) as? String else { return false }
        var settable: DarwinBoolean = false
        guard AXUIElementIsAttributeSettable(field, selectedText, &settable) == .success, settable.boolValue,
              AXUIElementSetAttributeValue(field, selectedText, text as CFString) == .success else { return false }
        for _ in 0..<3 {
            if let after = FocusInspector.attribute(field, valueAttribute) as? String, after != before { return true }
            // Unele aplicatii actualizeaza valoarea cu o mica intarziere.
            try? await Task.sleep(nanoseconds: 40_000_000)
        }
        return false
    }

    /// Aduce in fata aplicatia, fereastra si campul in care a inceput dictarea.
    private static func bringToFront(_ target: FocusSnapshot, app: NSRunningApplication) async -> Bool {
        activate(app)
        if let window = target.window?.element {
            _ = AXUIElementPerformAction(window, kAXRaiseAction as CFString)
            _ = AXUIElementSetAttributeValue(window, kAXMainAttribute as CFString, kCFBooleanTrue)
        }
        for _ in 0..<50 {
            if NSWorkspace.shared.frontmostApplication?.processIdentifier == target.pid { break }
            try? await Task.sleep(nanoseconds: 20_000_000)
        }
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target.pid else { return false }
        if let field = target.field?.element {
            _ = AXUIElementSetAttributeValue(field, kAXFocusedAttribute as CFString, kCFBooleanTrue)
        }
        // Fereastra si campul au nevoie de un moment ca sa devina active inainte de ⌘V.
        try? await Task.sleep(nanoseconds: 120_000_000)
        return true
    }

    /// Activeaza o aplicatie si prin NSRunningApplication, si prin Accessibility (hau-di nu e aplicatia activa).
    private static func activate(_ app: NSRunningApplication) {
        _ = app.activate(options: [])
        let element = AXUIElementCreateApplication(app.processIdentifier)
        _ = AXUIElementSetAttributeValue(element, kAXFrontmostAttribute as CFString, kCFBooleanTrue)
    }

    /// Pune textul in clipboard, trimite ⌘V, apoi reface continutul anterior al clipboard-ului.
    private func paste(_ text: String, restoreClipboard: Bool) async {
        let pasteboard = NSPasteboard.general
        let snapshot = restoreClipboard ? PasteboardSnapshot(pasteboard) : nil

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if restoreClipboard {
            // Managerii de clipboard (Raycast, Maccy, Paste...) ignora elementele marcate astfel.
            item.setData(Data(), forType: Self.transientType)
            item.setData(Data(), forType: Self.autoGeneratedType)
        }
        pasteboard.writeObjects([item])
        let ourChangeCount = pasteboard.changeCount

        try? await Task.sleep(nanoseconds: 15_000_000)
        Self.postKey(KeyboardLayout.pasteKeyCode, flags: .maskCommand)

        guard let snapshot else { return }
        // Unele aplicatii (Electron, browsere) citesc clipboard-ul asincron dupa ⌘V.
        try? await Task.sleep(nanoseconds: 500_000_000)
        if pasteboard.changeCount == ourChangeCount {
            snapshot.restore(to: pasteboard)
        }
    }

    /// Tasteaza textul prin evenimente Unicode (fara clipboard). Newline = ⇧↩ ca sa nu trimita mesaje in chat-uri.
    private func typeCharacters(_ text: String) async {
        let source = CGEventSource(stateID: .hidSystemState)
        let lines = text.components(separatedBy: "\n")
        for (index, line) in lines.enumerated() {
            var chunk: [UniChar] = []
            for character in line {
                let units = Array(String(character).utf16)
                if chunk.count + units.count > 16 {
                    Self.postUnicode(chunk, source: source)
                    chunk.removeAll()
                    try? await Task.sleep(nanoseconds: 6_000_000)
                }
                chunk.append(contentsOf: units)
            }
            if !chunk.isEmpty { Self.postUnicode(chunk, source: source) }
            if index < lines.count - 1 {
                try? await Task.sleep(nanoseconds: 6_000_000)
                Self.postKey(36, flags: .maskShift) // kVK_Return
            }
        }
    }

    private static func postUnicode(_ units: [UniChar], source: CGEventSource?) {
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false) else { return }
        down.keyboardSetUnicodeString(stringLength: units.count, unicodeString: units)
        up.keyboardSetUnicodeString(stringLength: units.count, unicodeString: units)
        markSynthetic(down, up)
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }

    private static func postKey(_ keyCode: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .hidSystemState)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false) else { return }
        down.flags = flags
        up.flags = flags
        markSynthetic(down, up)
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }

    private static func markSynthetic(_ events: CGEvent...) {
        for event in events {
            event.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
        }
    }
}

/// Copie completa a clipboard-ului (toate elementele si tipurile), pentru restaurare.
struct PasteboardSnapshot {
    private let items: [[(NSPasteboard.PasteboardType, Data)]]

    init(_ pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { (type, $0) }
            }
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
    }
}

// MARK: - Contextul campului activ (Accessibility API)

/// Referinta la un element Accessibility (fereastra, camp). Obiect CF imuabil: se poate trimite intre fire.
struct AXRef: @unchecked Sendable {
    let element: AXUIElement
}

struct FocusSnapshot: Sendable {
    var pid: pid_t = 0
    var appName: String?
    var bundleID: String?
    var windowTitle: String?
    var textBeforeCursor: String?
    var isSecureField = false
    /// Fereastra si campul in care a inceput dictarea: textul ajunge acolo, chiar daca utilizatorul a schimbat focusul.
    var window: AXRef?
    var field: AXRef?
}

enum FocusInspector {
    private static let focusedElement = "AXFocusedUIElement" as CFString
    private static let focusedWindow = "AXFocusedWindow" as CFString
    private static let title = "AXTitle" as CFString
    private static let value = "AXValue" as CFString
    private static let selectedRange = "AXSelectedTextRange" as CFString
    private static let subrole = "AXSubrole" as CFString
    private static let secureSubrole = "AXSecureTextField"

    /// Retine aplicatia, fereastra si campul activ (unde se va insera textul), titlul ferestrei si, optional,
    /// textul dinaintea cursorului. Apeluri IPC sincrone - se ruleaza in afara main thread-ului, cu timeout scurt.
    static func capture(pid: pid_t, appName: String?, bundleID: String?, includeTextBeforeCursor: Bool) -> FocusSnapshot {
        var snapshot = FocusSnapshot(pid: pid, appName: appName, bundleID: bundleID)
        guard AXIsProcessTrusted() else { return snapshot }

        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.25)

        if let window = element(app, focusedWindow) {
            AXUIElementSetMessagingTimeout(window, 0.25)
            snapshot.window = AXRef(element: window)
            snapshot.windowTitle = attribute(window, title) as? String
        }

        guard let field = element(app, focusedElement) else { return snapshot }
        AXUIElementSetMessagingTimeout(field, 0.25)
        if (attribute(field, subrole) as? String) == secureSubrole {
            // Campurile de parola nu se citesc si nu se retin.
            snapshot.isSecureField = true
            return snapshot
        }
        snapshot.field = AXRef(element: field)
        guard includeTextBeforeCursor, let text = attribute(field, value) as? String else { return snapshot }
        let nsText = text as NSString
        var cursor = nsText.length
        if let rangeRef = attribute(field, selectedRange), CFGetTypeID(rangeRef) == AXValueGetTypeID() {
            var range = CFRange()
            if AXValueGetValue(rangeRef as! AXValue, .cfRange, &range), range.location >= 0 {
                cursor = min(range.location, nsText.length)
            }
        }
        let start = max(0, cursor - 600)
        snapshot.textBeforeCursor = nsText.substring(with: NSRange(location: start, length: cursor - start))
        return snapshot
    }

    static func attribute(_ element: AXUIElement, _ name: CFString) -> CFTypeRef? {
        var result: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, name, &result) == .success else { return nil }
        return result
    }

    static func element(_ parent: AXUIElement, _ name: CFString) -> AXUIElement? {
        guard let ref = attribute(parent, name), CFGetTypeID(ref) == AXUIElementGetTypeID() else { return nil }
        return (ref as! AXUIElement)
    }
}
